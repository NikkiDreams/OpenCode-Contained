#!/usr/bin/env bash
# setup_shell.sh — Install  occontained shell functions for zsh or bash

set -euo pipefail
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
RED='\033[0;31m'
NC='\033[0m'

FUNCTIONS_FILE="$HOME/.local/bin/occontained-functions.sh"
SOURCE_LINE="source \"\$HOME/.local/bin/occontained-functions.sh\""

echo -e "${BLUE}OpenCode shell setup${NC}"
echo ""

# ── Detect current running shell ────────────────────────────────────────────────────────────
# Login shells appear with a leading dash ("-bash", "-zsh"), so strip it before matching.
CURRENT_SHELL="$(ps -p $$ -o comm=)"
CURRENT_SHELL="${CURRENT_SHELL#-}"
case "$CURRENT_SHELL" in
  zsh)
    RC_FILE="$HOME/.zshrc"
    SHELL_NAME="zsh"
    ;;
  bash)
    RC_FILE="$HOME/.bashrc"
    SHELL_NAME="bash"
    ;;
  fish)
    echo -e "${RED}Fish is not supported: the generated functions use bash syntax and fish cannot source them.${NC}"
    exit 1
    ;;
  *)
    RC_FILE="$HOME/.bashrc"
    SHELL_NAME="bash"
    ;;
esac

echo -e "${GREEN}Detected shell:${NC} ${SHELL_NAME} → will configure ${CYAN}${RC_FILE}${NC}"
echo ""
echo -e "${BLUE}Web mode requires a password. Set it once:${NC}"
echo -e '  export OPENCODE_SERVER_PASSWORD="$(openssl rand -hex 24)"'
echo -e "run.sh and Podman Compose also read it from ${CYAN}.env${NC} (git-ignored, see ${CYAN}.env.example${NC}); the shell functions read it from your environment."
echo ""

# ── Create functions file ────────────────────────────────────────────────────
mkdir -p "$HOME/.local/bin"

# --network=host is intentional: it lets the container reach local LLM runtimes
# and the internet directly. With host networking, port mappings are no-ops, so
# the port and the bind address are set on the server command inside the
# generated functions. Web mode binds 127.0.0.1 unless OPENCODE_BIND is set:
# host networking also shares the host loopback, so local LLM APIs are still
# reachable while the web UI stays off the LAN.
cat >"$FUNCTIONS_FILE" <<'EOF'
# occontained shell functions — generated by setup_shell.sh
# Run `~/OC_Contained/setup_shell.sh` again to update.

occontained() {
  # Web mode must not start without authentication.
  if [ -z "${OPENCODE_SERVER_PASSWORD:-}" ]; then
    echo "ERROR: OPENCODE_SERVER_PASSWORD is not set; web mode would start with no authentication." >&2
    echo 'Set it first:  export OPENCODE_SERVER_PASSWORD="$(openssl rand -hex 24)"' >&2
    echo "Or add it to your shell rc file so it persists. Terminal mode needs no password: occontained_tui" >&2
    return 1
  fi
  # Secrets are passed to podman as bare `-e NAME` (inherited from this
  # shell's environment) instead of `-e NAME=value`: command-line values land
  # in the podman process argv, readable by any local user through `ps`.
  # GH_TOKEN is exported only when set: an exported empty value would
  # clutter this shell, and podman passes unset variables through as absent.
  if [ -n "${GH_TOKEN:-}" ]; then export GH_TOKEN; fi
  export OPENCODE_SERVER_USERNAME="${OPENCODE_SERVER_USERNAME:-opencode}"
  export OPENCODE_SERVER_PASSWORD
  podman run -d \
    --name occontained \
    --rm \
    --user "$(id -u):$(id -g)" \
    --network=host \
    --memory=12g --memory-swap=15g \
    --pids-limit=512 \
    --cpus=6 \
    -w /workspace \
    -v "${OPENCODE_PATH:-$(pwd)}:/workspace" \
    -v "$HOME/.ssh/id_ed25519:/home/occontained/.ssh/id_ed25519:ro" \
    -v "$HOME/.config/opencode:/home/occontained/.config/opencode" \
    -v "$HOME/.local/share/opencode/auth.json:/home/occontained/.local/share/opencode/auth.json" \
    -e "HOME=/home/occontained" \
    -e "XDG_CONFIG_HOME=/home/occontained/.config" \
    -e "XDG_DATA_HOME=/home/occontained/.local/share" \
    -e GH_TOKEN \
    -e OPENCODE_SERVER_USERNAME \
    -e OPENCODE_SERVER_PASSWORD \
    ghcr.io/nikkidreams/opencode-contained:latest web --hostname "${OPENCODE_BIND:-127.0.0.1}" --port "${OPENCODE_PORT:-4096}"
}

occontained_tui() {
  # Same bare `-e NAME` inheritance as occontained: keep secrets out of argv.
  if [ -n "${GH_TOKEN:-}" ]; then export GH_TOKEN; fi
  export OPENCODE_SERVER_USERNAME="${OPENCODE_SERVER_USERNAME:-opencode}"
  export OPENCODE_SERVER_PASSWORD="${OPENCODE_SERVER_PASSWORD:-}"
  podman run -it \
    --rm \
    --name occontained-tui \
    --user "$(id -u):$(id -g)" \
    --network=host \
    --memory=12g --memory-swap=15g \
    --pids-limit=512 \
    --cpus=6 \
    -w /workspace \
    -v "${OPENCODE_PATH:-$(pwd)}:/workspace" \
    -v "$HOME/.ssh/id_ed25519:/home/occontained/.ssh/id_ed25519:ro" \
    -v "$HOME/.config/opencode:/home/occontained/.config/opencode" \
    -v "$HOME/.local/share/opencode/auth.json:/home/occontained/.local/share/opencode/auth.json" \
    -e "HOME=/home/occontained" \
    -e "XDG_CONFIG_HOME=/home/occontained/.config" \
    -e "XDG_DATA_HOME=/home/occontained/.local/share" \
    -e GH_TOKEN \
    -e OPENCODE_SERVER_USERNAME \
    -e OPENCODE_SERVER_PASSWORD \
    ghcr.io/nikkidreams/opencode-contained:latest
}
EOF

# chmod +x "$FUNCTIONS_FILE"
echo -e "${GREEN}Functions written to:${NC} ${CYAN}${FUNCTIONS_FILE}${NC}"

# ── Add source line to rc file (idempotent) ─────────────────────────────────
if grep -qF "occontained-functions.sh" "$RC_FILE" 2>/dev/null; then
  echo -e "${YELLOW}Source line already present in ${RC_FILE} — skipping.${NC}"
else
  echo "" >>"$RC_FILE"
  echo "#occontained" >>"$RC_FILE"
  echo "$SOURCE_LINE" >>"$RC_FILE"
  echo -e "${GREEN}Source line added to:${NC} ${CYAN}${RC_FILE}${NC}"
fi

echo ""
echo -e "${GREEN}Done!${NC} Reload your shell with:"
echo -e "  ${CYAN}source ${RC_FILE}${NC}"
echo ""
echo -e "${BLUE}Available commands after reload:${NC}"
echo -e "  ${CYAN}occontained${NC}   — start web mode (detached)"
echo -e "  ${CYAN}occontained_tui${NC}  — start TUI mode (interactive)"
